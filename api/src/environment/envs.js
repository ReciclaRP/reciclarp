let ESCALATION_TOKEN = process.env.RECICLA_ESCALATION_TOKEN;

if(!ESCALATION_TOKEN) {
  let toknums = new Uint32Array(4);
  let tok = "";

  crypto.getRandomValues(toknums);
  
  for(let num of toknums) {
    tok += String(num)
  }

  ESCALATION_TOKEN = tok;

  logger.info(`Environment variable RECICLA_ESCALATION_TOKEN not provided. Autogenerated: ${ESCALATION_TOKEN}`);
}

